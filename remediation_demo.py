"""LogSage-inspired end-to-end remediation experiment (unofficial).

Safe constraints:
- Always creates synthetic, runnable Python projects inside --out/workspaces.
- Never edits the original LogSage dataset or user's repositories.
- The LLM can only select an allowlisted repair tool; it cannot execute shell code.
- A repair is counted as successful only when the rerun passes independently.

The public LogSage dataset lacks complete source checkouts and runnable pipelines.
Therefore these controlled repairs are a SEPARATE demonstration, not the
published ByteDance remediation benchmark (and not RQ1 or RQ2 results).
"""
from __future__ import annotations

import argparse
import csv
import difflib
import json
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from experiment import query_ollama

TOOLS = {
    "fix_add_operator": "Unit test failure: in src/calculator.py, fix add(a,b) returning a-b rather than a+b.",
    "lint_fix": "Static quality gate: remove trailing spaces/tabs at line endings in src/*.py.",
    "no_fix": "No provided tool can safely resolve the identified failure.",
}

SOURCES = {
    "unit": {
        "src/calculator.py": '"""Arithmetic module."""\n\ndef add(a: int, b: int) -> int:\n    return a - b\n',
        "tests/test_calculator.py": 'import unittest\nfrom src.calculator import add\n\nclass CalculatorTests(unittest.TestCase):\n    def test_positive(self):\n        self.assertEqual(add(2, 3), 5)\n\n    def test_zero(self):\n        self.assertEqual(add(0, 4), 4)\n\n    def test_negative(self):\n        self.assertEqual(add(-2, 3), 1)\n',
        "src/__init__.py": "",
    },
    "lint": {
        "src/report.py": 'def title(text: str) -> str:   \n    return text.strip().title()  \n',
        "src/__init__.py": "",
        "tests/test_report.py": 'import unittest\nfrom src.report import title\n\nclass ReportTests(unittest.TestCase):\n    def test_title(self):\n        self.assertEqual(title("  hello world "), "Hello World")\n',
        "scripts/lint_gate.py": '''from pathlib import Path
import sys

bad = []
for path in sorted(Path("src").rglob("*.py")):
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.rstrip(" \\t") != line:
            bad.append(f"{path.as_posix()}:{lineno}: TRAILING_WHITESPACE")
if bad:
    print("\\n".join(bad))
    sys.exit(1)
print("Lint gate passed")
''',
    },
    "unsupported": {
        "src/service.py": 'def status() -> str:\n    return "offline"\n',
        "src/__init__.py": "",
        "tests/test_service.py": 'import unittest\nfrom src.service import status\n\nclass ServiceTests(unittest.TestCase):\n    def test_status(self):\n        self.assertEqual(status(), "online")\n',
    },
}


def create_workspace(out: Path, scenario: str) -> Path:
    """Only replace generated workspace within --out, never source projects."""
    ws = out.resolve() / "workspaces" / scenario
    ws.parent.mkdir(parents=True, exist_ok=True)
    if ws.exists():
        if not ws.is_dir() or ws.is_symlink() or not (ws / ".logsage_generated_workspace").is_file():
            raise ValueError(f"Workspace is not marked as generated by this demo; refusing to erase: {ws}")
        shutil.rmtree(ws)
    ws.mkdir(parents=True, exist_ok=True)
    (ws / ".logsage_generated_workspace").write_text("Generated only by remediation_demo.py\n", encoding="utf-8")
    for relative, text in SOURCES[scenario].items():
        file = ws / relative
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text, encoding="utf-8")
    return ws


def run_cmd(args: list[str], cwd: Path, timeout: int = 60) -> dict:
    before = time.monotonic()
    try:
        done = subprocess.run(args, cwd=cwd, capture_output=True, text=True, errors="replace", timeout=timeout)
        return {"exit_code": done.returncode, "output": (done.stdout + "\n" + done.stderr)[-16000:],
                "seconds": round(time.monotonic()-before, 3)}
    except subprocess.TimeoutExpired:
        return {"exit_code": 124, "output": f"Stage timed out after {timeout} s", "seconds": timeout}


def run_gate(ws: Path, scenario: str) -> dict:
    if scenario == "lint":
        gate = run_cmd([sys.executable, "scripts/lint_gate.py"], ws)
        if gate["exit_code"] != 0:
            return {"stage": "STATIC_ANALYSIS", **gate}
    gate = run_cmd([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"], ws)
    return {"stage": "UNIT_TESTS", **gate}


def run_build(ws: Path) -> dict:
    return {"stage": "BUILD", **run_cmd([sys.executable, "-m", "compileall", "-q", "src"], ws)}


def local_diagnosis(scenario: str, log: str) -> str:
    """Offline rule-baseline for smoke tests; does not use artificial 'AI' claims."""
    if scenario == "unit":
        return "UNIT_TESTS: add(2,3) returned -1 instead of 5. The add function uses subtraction instead of addition."
    if scenario == "lint":
        return "STATIC_ANALYSIS: report.py has trailing whitespace causing the quality gate to fail."
    return "UNIT_TESTS: test_status expects online but gets offline; no allowed remediation tool handles this failure."


def source_snippet(ws: Path, scenario: str) -> str:
    relative = {"unit": "src/calculator.py", "lint": "src/report.py", "unsupported": "src/service.py"}[scenario]
    return f"File {relative}:\n{(ws / relative).read_text(encoding='utf-8')}"


def select_knowledge(log: str, snippet: str) -> list[dict[str, str]]:
    """Tiny local knowledge retrieval; NOT the paper's enterprise multi-route RAG."""
    haystack = (log + '\n' + snippet).lower()
    knowledge = [
        {"source": "LOCAL_TOOL_GUIDE/addition", "text": TOOLS["fix_add_operator"]},
        {"source": "LOCAL_TOOL_GUIDE/lint", "text": TOOLS["lint_fix"]},
    ]
    return [doc for doc in knowledge if
            ("calculator" in haystack and "addition" in doc["source"])
            or ("trailing_whitespace" in haystack and "lint" in doc["source"])]


def extract_json_object(text: str) -> dict[str, Any]:
    """Decode one JSON object even if a local model wraps it in prose/fences."""
    decoder = json.JSONDecoder()
    for match in re.finditer(r'\{', text):
        try:
            value, _ = decoder.raw_decode(text[match.start():])
        except json.JSONDecodeError:
            continue
        if isinstance(value, dict):
            return value
    raise ValueError("The model did not return a JSON object")


def pick_tool_llm(diagnosis: str, log: str, source: str, knowledge: list[dict], model: str,
                  ollama_url: str) -> tuple[str, str, str]:
    guide = '\n'.join(f"- {name}: {desc}" for name,desc in TOOLS.items())
    prompt = f'''Root cause diagnosis:\n{diagnosis[:2200]}\n\nFailure evidence:\n{log[-3000:]}\n\nSource code (read only):\n{source[:1800]}\n\nRetrieved knowledge:\n{json.dumps(knowledge,ensure_ascii=False)[:1500]}\n\nAvailable tools:\n{guide}\n\nRespond with ONLY JSON: {{"tool": "one exact available tool name", "reason": "brief evidence"}}.\nNever choose a tool unless evidence supports its preconditions.\n'''
    raw = query_ollama("You are a CI/CD remediation planner. Choose exactly one allowlisted tool. Never run commands.",
                       prompt, model, ollama_url)
    obj = extract_json_object(raw)
    tool = str(obj.get("tool", "no_fix"))
    if tool not in TOOLS:
        raise ValueError(f"Invalid tool selected: {tool!r}")
    return tool, str(obj.get("reason", "")), raw


def apply_tool(ws: Path, tool: str, scenario: str) -> dict:
    """Predetermined/allowlisted tools, no arbitrary generated commands or repo access."""
    if tool == "no_fix":
        return {"applied": False, "error": "No applicable tool was selected", "patch": ""}
    if tool == "fix_add_operator":
        target = ws / "src" / "calculator.py"
        if scenario != "unit" or not target.is_file():
            return {"applied": False, "error": "Tool not applicable to this scenario", "patch": ""}
        before = target.read_text(encoding="utf-8")
        if before.count("    return a - b") != 1:
            return {"applied": False, "error": "Expected bug pattern not present; no change", "patch": ""}
        after = before.replace("    return a - b", "    return a + b")
    elif tool == "lint_fix":
        if scenario != "lint":
            return {"applied": False, "error": "Tool not applicable to this scenario", "patch": ""}
        target = ws / "src" / "report.py"
        if not target.is_file():
            return {"applied": False, "error": "Target not present", "patch": ""}
        before = target.read_text(encoding="utf-8")
        after = "\n".join(line.rstrip(' \t') for line in before.splitlines()) + '\n'
        if after == before:
            return {"applied": False, "error": "No trailing whitespace found", "patch": ""}
    else:
        raise ValueError("Unsupported tool")
    patch = ''.join(difflib.unified_diff(before.splitlines(keepends=True), after.splitlines(keepends=True),
                                         fromfile=f"before/{target.relative_to(ws).as_posix()}",
                                         tofile=f"after/{target.relative_to(ws).as_posix()}"))
    target.write_text(after, encoding="utf-8")
    # Source changes can keep mtime and byte count, causing stale .pyc on fast reruns.
    for cache in ws.rglob("__pycache__"):
        if cache.is_dir() and not cache.is_symlink():
            shutil.rmtree(cache)
    return {"applied": True, "error": "", "patch": patch,
            "file": target.relative_to(ws).as_posix()}


def run_scenario(scenario: str, *, mode: str, model: str, ollama_url: str, apply: bool,
                 out: Path) -> dict:
    started = time.monotonic()
    ws = create_workspace(out, scenario)
    initial = run_gate(ws, scenario)
    record: dict[str, Any] = {
        "scenario": scenario, "mode": mode, "model": model if mode == "ollama" else None,
        "workspace": str(ws), "initial": initial, "diagnosis": "", "knowledge": [],
        "selected_tool": "no_fix", "tool_reason": "", "model_tool_response": "",
        "remediation": {"applied": False, "patch": "", "error": "Not attempted"},
        "recheck": None, "build": None, "success": False,
    }
    print(f"[{scenario}] STAGE {initial['stage']} (antes): {'PASS' if initial['exit_code'] == 0 else 'FAIL'}", flush=True)
    if initial["exit_code"] == 0:
        record["build"] = run_build(ws)
        record["success"] = record["build"]["exit_code"] == 0
        record["seconds"] = round(time.monotonic()-started, 3)
        return record

    snippet = source_snippet(ws, scenario)
    record["knowledge"] = select_knowledge(initial["output"], snippet)
    if mode == "rule":
        record["diagnosis"] = local_diagnosis(scenario, initial["output"])
        tool = {"unit": "fix_add_operator", "lint": "lint_fix", "unsupported": "no_fix"}[scenario]
        record["selected_tool"] = tool
        record["tool_reason"] = "Offline deterministic rule baseline (NOT an LLM prediction)"
    else:
        rca_prompt = f"Failed stage: {initial['stage']}\nLogs:\n{initial['output'][-3500:]}\n\n{snippet}\nIdentify the failing test or check and concrete root cause. Do NOT propose repairs."
        record["diagnosis"] = query_ollama(
            "You diagnose a failed CI/CD stage. Report the actual error and root cause using only evidence.",
            rca_prompt, model, ollama_url)
        try:
            tool, reason, response = pick_tool_llm(record["diagnosis"], initial["output"], snippet,
                                                   record["knowledge"], model, ollama_url)
            record["selected_tool"], record["tool_reason"], record["model_tool_response"] = tool, reason, response
        except (ValueError, RuntimeError) as exc:
            record["tool_reason"] = "Invalid tool-selection response: " + str(exc)
    print(f"[{scenario}] AUX_REMEDIACION: herramienta elegida = {record['selected_tool']}", flush=True)
    if apply:
        record["remediation"] = apply_tool(ws, record["selected_tool"], scenario)
        if record["remediation"]["applied"]:
            print(f"[{scenario}] AUX_REMEDIACION: parche aplicado a {record['remediation']['file']}", flush=True)
            record["recheck"] = run_gate(ws, scenario)
            print(f"[{scenario}] RETEST: {'PASS' if record['recheck']['exit_code'] == 0 else 'FAIL'}", flush=True)
            if record["recheck"]["exit_code"] == 0:
                record["build"] = run_build(ws)
                print(f"[{scenario}] STAGE BUILD: {'PASS' if record['build']['exit_code'] == 0 else 'FAIL'}", flush=True)
                record["success"] = record["build"]["exit_code"] == 0
    else:
        record["remediation"]["error"] = "Preview mode: omit --apply to prevent modifications"
    record["seconds"] = round(time.monotonic()-started, 3)
    return record


def write_results(out: Path, records: list[dict], mode: str) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    for record in records:
        (out / f"{record['scenario']}_detail.json").write_text(json.dumps(record, indent=2, ensure_ascii=False), encoding="utf-8")
        (out / f"{record['scenario']}_patch.diff").write_text(record["remediation"].get("patch", ""), encoding="utf-8")
    columns = ["scenario", "mode", "initial_failed", "selected_tool", "tool_applied", "retest_passed", "pipeline_recovered", "seconds"]
    with (out / "remediation_cases.csv").open("w", newline="", encoding="utf-8-sig") as fh:
        writer = csv.DictWriter(fh, fieldnames=columns)
        writer.writeheader()
        for r in records:
            writer.writerow({"scenario": r["scenario"], "mode": mode,
                             "initial_failed": int(r["initial"]["exit_code"] != 0),
                             "selected_tool": r["selected_tool"],
                             "tool_applied": int(r["remediation"]["applied"]),
                             "retest_passed": int(r["recheck"] is not None and r["recheck"]["exit_code"] == 0),
                             "pipeline_recovered": int(r["success"]), "seconds": r["seconds"]})
    n = len(records)
    applied = sum(r["remediation"]["applied"] for r in records)
    fixed = sum(r["success"] and r["initial"]["exit_code"] != 0 for r in records)
    summary = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(), "mode": mode,
        "total_cases": n, "initial_failures": sum(r["initial"]["exit_code"] != 0 for r in records),
        "tools_selected": sum(r["selected_tool"] != "no_fix" for r in records),
        "repairs_applied": applied, "successful_repairs": fixed,
        "tool_coverage_rate": round(sum(r["selected_tool"] != "no_fix" for r in records)/n, 4) if n else None,
        "rerun_success_rate": round(fixed/applied, 4) if applied else None,
        "end_to_end_recovery_rate": round(fixed/n, 4) if n else None,
        "note": "Synthetic runnable scenarios. This is an unofficial LogSage-inspired tool-calling remediation demo, not the industrial evaluation of Xu et al. Offline rule mode is NOT AI.",
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False), flush=True)
    print("Evidence directory:", out.resolve(), flush=True)
    return summary


def main() -> None:
    p = argparse.ArgumentParser(description="Experiment: failed CI/CD stage -> RCA -> tool -> repair -> rerun")
    p.add_argument("--mode", choices=["ollama", "rule"], default="ollama",
                   help="ollama=local AI; rule=offline technical smoke test without AI")
    p.add_argument("--model", default="qwen2.5-coder:3b")
    p.add_argument("--ollama-url", default="http://127.0.0.1:11434/api/chat")
    p.add_argument("--scenario", choices=["unit", "lint", "unsupported", "both", "all"], default="both")
    p.add_argument("--out", type=Path, default=Path("results/remediation-demo"))
    p.add_argument("--apply", action="store_true", help="Explicitly allow tools to edit generated sandbox source")
    args = p.parse_args()
    names = ["unit", "lint"] if args.scenario == "both" else ["unit", "lint", "unsupported"] if args.scenario == "all" else [args.scenario]
    out = args.out.resolve()
    records = []
    for name in names:
        try:
            record = run_scenario(name, mode=args.mode, model=args.model,
                                  ollama_url=args.ollama_url, apply=args.apply, out=out)
        except Exception as exc:
            print(f"ERROR in scenario {name}: {type(exc).__name__}: {exc}", file=sys.stderr, flush=True)
            record = {"scenario": name, "mode": args.mode, "initial": {"exit_code": 1},
                      "selected_tool": "no_fix", "remediation": {"applied": False, "error": str(exc), "patch": ""},
                      "recheck": None, "build": None, "success": False,
                      "seconds": 0, "error": f"{type(exc).__name__}: {exc}"}
        records.append(record)
    write_results(out, records, args.mode)
    if any(r.get("error") for r in records):
        sys.exit(2)

if __name__ == "__main__":
    main()
